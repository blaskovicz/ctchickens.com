// Copies generated/shared files into functions/src before `tsc` runs.
// `firebase deploy` only uploads the functions/ directory, so anything
// functions code needs from elsewhere in the repo has to be copied in here
// first rather than imported across directories. Edit the source files
// listed below, not their generated copies under src/.
const fs = require('fs');
const path = require('path');

function copyFileWithBanner(fromPath, toPath) {
  const contents = fs.readFileSync(fromPath, 'utf8');
  const banner = `// Generated by prebuild — edit ${fromPath} instead.\n`;
  fs.writeFileSync(toPath, banner + contents);
}

copyFileWithBanner(
  path.join(__dirname, '../../src/shared-config.ts'),
  path.join(__dirname, '../src/shared-config.ts')
);

copyFileWithBanner(
  path.join(__dirname, '../../scripts/lib/featured-card.cjs'),
  path.join(__dirname, '../src/featuredCard.cjs')
);

fs.cpSync(
  path.join(__dirname, '../../scripts/lib/fonts'),
  path.join(__dirname, '../src/fonts'),
  { recursive: true }
);
